#!/usr/bin/env python
"""
PAAC-VN — run full clustering grid from the verified embedding manifest.

Operational wrapper only. It does NOT change any clustering methodology.

Rules:
- Read results/audit/embedding_manifest.csv.
- Require exactly 32 rows with status == COMPLETE.
- Run pipeline/cluster.py sequentially, one configuration at a time.
- Official outputs go to results/labels/.
- If all 5 expected outputs for a config already exist, skip it (resume-safe).
- If only some outputs exist, STOP to avoid mixing partial/stale artifacts.
- Stop immediately on the first failed clustering subprocess.
- Write an execution log to results/clustering_run_log.csv.
"""

from __future__ import annotations

import argparse
import csv
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

EXPECTED_CONFIGS = 32
EXPECTED_OUTPUT_SUFFIXES = [
    "__kmeans_main.npz",
    "__kmeans_diag.npz",
    "__agglomerative.npy",
    "__linkage.npy",
    "__cluster_meta.json",
]


def fmt(seconds: float) -> str:
    seconds = float(seconds)
    if seconds < 60:
        return f"{seconds:.1f}s"
    m, s = divmod(seconds, 60)
    if m < 60:
        return f"{int(m)}m {s:.1f}s"
    h, m = divmod(m, 60)
    return f"{int(h)}h {int(m)}m {s:.1f}s"


def expected_paths(out_dir: Path, stem: str) -> list[Path]:
    return [out_dir / f"{stem}{suffix}" for suffix in EXPECTED_OUTPUT_SUFFIXES]


def append_log(log_path: Path, row: dict) -> None:
    log_path.parent.mkdir(parents=True, exist_ok=True)
    exists = log_path.exists()
    with log_path.open("a", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "timestamp_utc",
                "index",
                "experiment",
                "representation",
                "language",
                "truncation",
                "status",
                "runtime_seconds",
                "returncode",
                "note",
            ],
        )
        if not exists:
            writer.writeheader()
        writer.writerow(row)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", type=Path, default=Path("."))
    ap.add_argument(
        "--manifest",
        type=Path,
        default=Path("results/audit/embedding_manifest.csv"),
    )
    ap.add_argument(
        "--out-dir",
        type=Path,
        default=Path("results/labels"),
    )
    ap.add_argument(
        "--log",
        type=Path,
        default=Path("results/clustering_run_log.csv"),
    )
    ap.add_argument(
        "--distance-block-size",
        type=int,
        default=512,
        help="Operational block size passed through to cluster.py.",
    )
    ap.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the 32 commands without executing them.",
    )
    args = ap.parse_args()

    repo = args.repo.resolve()

    manifest = args.manifest
    if not manifest.is_absolute():
        manifest = repo / manifest

    out_dir = args.out_dir
    if not out_dir.is_absolute():
        out_dir = repo / out_dir

    log_path = args.log
    if not log_path.is_absolute():
        log_path = repo / log_path

    cluster_py = repo / "pipeline" / "cluster.py"

    if not manifest.exists():
        raise FileNotFoundError(f"Manifest not found: {manifest}")
    if not cluster_py.exists():
        raise FileNotFoundError(f"cluster.py not found: {cluster_py}")

    df = pd.read_csv(manifest)

    required = {
        "experiment",
        "representation",
        "language",
        "truncation",
        "status",
    }
    missing_cols = required - set(df.columns)
    if missing_cols:
        raise ValueError(f"Manifest missing columns: {sorted(missing_cols)}")

    complete = df[df["status"].astype(str).str.upper() == "COMPLETE"].copy()

    if len(df) != EXPECTED_CONFIGS:
        raise ValueError(
            f"Manifest must contain exactly {EXPECTED_CONFIGS} expected configurations; "
            f"found {len(df)} rows."
        )

    if len(complete) != EXPECTED_CONFIGS:
        counts = df["status"].value_counts(dropna=False).to_dict()
        raise RuntimeError(
            f"Refusing full clustering: expected {EXPECTED_CONFIGS}/{EXPECTED_CONFIGS} COMPLETE, "
            f"found {len(complete)} COMPLETE. Status counts={counts}"
        )

    # Preserve manifest order: TN1 then TN2 as generated by audit.
    configs = complete[
        ["experiment", "representation", "language", "truncation"]
    ].to_dict("records")

    out_dir.mkdir(parents=True, exist_ok=True)

    print("=" * 78)
    print("PAAC-VN FULL CLUSTERING GRID")
    print(f"manifest        : {manifest}")
    print(f"verified configs: {len(configs)}/{EXPECTED_CONFIGS} COMPLETE")
    print(f"cluster.py      : {cluster_py}")
    print(f"official output : {out_dir}")
    print(f"log             : {log_path}")
    print("=" * 78)

    total_start = time.perf_counter()
    executed = 0
    skipped = 0

    for idx, cfg in enumerate(configs, start=1):
        exp = str(cfg["experiment"])
        rid = str(cfg["representation"])
        lang = str(cfg["language"])
        trunc = str(cfg["truncation"])

        stem = f"{exp}__{rid}__{lang}__{trunc}"
        paths = expected_paths(out_dir, stem)
        existing = [p.exists() for p in paths]

        print()
        print(f"[{idx:02d}/{EXPECTED_CONFIGS}] {stem}")

        if all(existing):
            skipped += 1
            print("  -> SKIP: all 5 official clustering artifacts already exist.")
            append_log(
                log_path,
                {
                    "timestamp_utc": datetime.now(timezone.utc).isoformat(),
                    "index": idx,
                    "experiment": exp,
                    "representation": rid,
                    "language": lang,
                    "truncation": trunc,
                    "status": "SKIPPED_COMPLETE",
                    "runtime_seconds": 0.0,
                    "returncode": 0,
                    "note": "All 5 expected outputs already exist.",
                },
            )
            continue

        if any(existing):
            present = [p.name for p, ok in zip(paths, existing) if ok]
            missing = [p.name for p, ok in zip(paths, existing) if not ok]
            raise RuntimeError(
                "Partial official outputs detected. Refusing to continue.\n"
                f"Configuration: {stem}\n"
                f"Present: {present}\n"
                f"Missing: {missing}\n"
                "Resolve the partial run explicitly before resuming."
            )

        cmd = [
            sys.executable,
            str(cluster_py),
            "--repo",
            str(repo),
            "--exp",
            exp,
            "--repr",
            rid,
            "--lang",
            lang,
            "--trunc",
            trunc,
            "--out-dir",
            str(out_dir),
            "--distance-block-size",
            str(args.distance_block_size),
        ]

        print("  ->", " ".join(cmd))

        if args.dry_run:
            continue

        t0 = time.perf_counter()
        proc = subprocess.run(cmd, cwd=repo)
        seconds = time.perf_counter() - t0

        if proc.returncode != 0:
            append_log(
                log_path,
                {
                    "timestamp_utc": datetime.now(timezone.utc).isoformat(),
                    "index": idx,
                    "experiment": exp,
                    "representation": rid,
                    "language": lang,
                    "truncation": trunc,
                    "status": "FAILED",
                    "runtime_seconds": round(seconds, 6),
                    "returncode": proc.returncode,
                    "note": "cluster.py returned non-zero; grid stopped immediately.",
                },
            )
            raise SystemExit(
                f"FAILED at [{idx}/{EXPECTED_CONFIGS}] {stem}, "
                f"returncode={proc.returncode}. Full grid stopped."
            )

        # Require the subprocess to have created all 5 outputs.
        missing_after = [p for p in paths if not p.exists()]
        if missing_after:
            append_log(
                log_path,
                {
                    "timestamp_utc": datetime.now(timezone.utc).isoformat(),
                    "index": idx,
                    "experiment": exp,
                    "representation": rid,
                    "language": lang,
                    "truncation": trunc,
                    "status": "FAILED_MISSING_OUTPUT",
                    "runtime_seconds": round(seconds, 6),
                    "returncode": proc.returncode,
                    "note": "Subprocess exited 0 but expected artifacts are missing.",
                },
            )
            raise RuntimeError(
                f"{stem}: cluster.py exited successfully but missing outputs: "
                f"{[p.name for p in missing_after]}"
            )

        executed += 1
        append_log(
            log_path,
            {
                "timestamp_utc": datetime.now(timezone.utc).isoformat(),
                "index": idx,
                "experiment": exp,
                "representation": rid,
                "language": lang,
                "truncation": trunc,
                "status": "COMPLETE",
                "runtime_seconds": round(seconds, 6),
                "returncode": proc.returncode,
                "note": "",
            },
        )

        elapsed = time.perf_counter() - total_start
        print(f"  -> COMPLETE in {fmt(seconds)} | elapsed grid time {fmt(elapsed)}")

    if args.dry_run:
        print()
        print(f"DRY RUN COMPLETE: {len(configs)} commands validated; nothing executed.")
        return

    total_seconds = time.perf_counter() - total_start

    print()
    print("=" * 78)
    print("FULL CLUSTERING GRID FINISHED")
    print(f"executed : {executed}")
    print(f"skipped  : {skipped}")
    print(f"total    : {executed + skipped}/{EXPECTED_CONFIGS}")
    print(f"runtime  : {fmt(total_seconds)}")
    print(f"outputs  : {out_dir}")
    print(f"log      : {log_path}")
    print("=" * 78)


if __name__ == "__main__":
    main()
